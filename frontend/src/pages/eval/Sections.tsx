import type { ColumnDef } from "@tanstack/react-table";
import { DataTable } from "../../components/ui/DataTable";
import { EmptyState } from "../../components/ui/EmptyState";
import { Panel } from "../../components/ui/Panel";
import { StatusBadge } from "../../components/ui/StatusBadge";
import { Tag } from "../../components/ui/Tag";
import type { CountSummary, EvalImageResult, EvalResults } from "../../types/api";

const num = "font-mono tabular-nums";
export const DASH = <span className="font-mono text-fm-faint">—</span>;
export const pctOrDash = (v: number | null | undefined) => (v === null || v === undefined ? "—" : (v * 100).toFixed(1));
const dec = (v: number | null | undefined, digits = 2) => (v === null || v === undefined ? DASH : <span className={num}>{v.toFixed(digits)}</span>);
const int = (v: number | null | undefined) => (v === null || v === undefined ? DASH : <span className={num}>{v}</span>);

export function SummaryLine({ s }: { s: CountSummary }) {
  return (
    <p className="border-t border-fm-border px-3 py-2 text-[11.5px] text-fm-muted">
      Exact-match accuracy <span className={num}>{pctOrDash(s.accuracy)}{s.accuracy === null ? "" : "%"}</span>{" "}
      (<span className={num}>{s.correct}</span> of <span className={num}>{s.measured}</span> measured), mean absolute error{" "}
      {dec(s.mean_abs_error)}. Unmeasured rows are left out, not counted wrong.
    </p>
  );
}

const imageCols: ColumnDef<EvalImageResult, unknown>[] = [
  { accessorKey: "id", header: "Image", cell: (i) => <span className="font-mono">{i.getValue<string>()}</span> },
  { accessorKey: "phrase", header: "SAM noun phrase", cell: (i) => <span className="font-mono text-fm-info">“{i.getValue<string>()}”</span> },
  { accessorKey: "prompted_count", header: "Prompted", meta: { align: "right" }, cell: (i) => <span className={`${num} text-fm-muted`}>{i.getValue<number>()}</span> },
  { accessorKey: "true_count", header: "True (human)", meta: { align: "right" }, cell: (i) => int(i.getValue<number>()) },
  { accessorKey: "sam_count", header: "SAM", meta: { align: "right" }, cell: (i) => int(i.getValue<number | null>()) },
  {
    accessorKey: "correct", header: "Result",
    cell: (i) => {
      const v = i.getValue<boolean | null>();
      return v === null ? DASH : v ? <StatusBadge signal="verified" label="PASS" size="sm" /> : <StatusBadge signal="fraud" label="FAIL" size="sm" />;
    },
  },
];

/** Synthetic Muse Image stills scored against a human-confirmed count. Never evidence. */
export function ImageEvalPanel({ results }: { results: EvalResults | null }) {
  const img = results?.images;
  return (
    <Panel
      index="04" title="Count accuracy on eval images" subtitle="SAM count vs human-confirmed count" padded={false} className="mt-3"
      actions={<Tag tone="review" title="Generated by muse-image-1.0 for testing; never used as evidence">SYNTHETIC</Tag>}
    >
      {!img || img.images_total === 0 ? (
        <EmptyState title="No eval images yet" description="Generate them with scripts/gen_eval_images.py, confirm the counts by eye, then run scripts/run_eval.py." />
      ) : (
        <>
          <p className="border-b border-fm-border px-3 py-2 text-[11.5px] text-fm-muted">
            <span className={num}>{img.images_confirmed}</span> of <span className={num}>{img.images_total}</span> images have a human-confirmed
            count; only those are scored. The prompted count is what the image model was asked for, not ground truth.
          </p>
          {img.rows.length > 0 ? <DataTable<EvalImageResult> columns={imageCols} data={img.rows} label="Count accuracy on synthetic eval images" /> : null}
          <SummaryLine s={img.summary} />
        </>
      )}
    </Panel>
  );
}

export function CostPanel({ results }: { results: EvalResults | null }) {
  const c = results?.cost;
  const money = (v: number | null | undefined) => (v === null || v === undefined ? DASH : <span className={num}>{v.toFixed(4)} {c?.currency ?? ""}</span>);
  return (
    <Panel index="06" title="Cost per delivery" subtitle="from model_calls tokens and configured rates" className="mt-3">
      {!c ? (
        <p className="text-[12px] text-fm-muted">Run scripts/run_eval.py to measure token usage and cost.</p>
      ) : (
        <dl className="grid gap-x-6 gap-y-2 text-[12px] sm:grid-cols-2 lg:grid-cols-4">
          <div><dt className="fm-label">Deliveries processed</dt><dd className={num}>{c.deliveries_processed}</dd></div>
          <div><dt className="fm-label">Tokens in / out</dt><dd className={num}>{c.total_input_tokens} / {c.total_output_tokens}</dd></div>
          <div><dt className="fm-label">Total cost</dt><dd>{money(c.total_cost)}</dd></div>
          <div><dt className="fm-label">Per delivery</dt><dd>{money(c.cost_per_delivery)}</dd></div>
        </dl>
      )}
      {c && !c.rates_configured && (
        <p className="mt-2 text-[11.5px] text-fm-muted">No prices are configured, so cost is not measured (set MODEL_COST_RATES and MODEL_COST_CURRENCY).</p>
      )}
    </Panel>
  );
}

export function AgentPanel({ results }: { results: EvalResults | null }) {
  const agent = results?.verdicts.agent ?? null;
  return (
    <Panel index="07" title="Decision agent vs ground truth" subtitle="stored agent decisions, reported separately from the served Python recompute" className="mt-3">
      {agent ? (
        <p className="text-[12px] text-fm-muted">
          <span className={num}>{agent.cases_correct}</span> of <span className={num}>{agent.cases_total}</span> correct, accuracy{" "}
          <span className={num}>{pctOrDash(agent.accuracy)}%</span>; macro precision {dec(agent.macro_precision)}, recall {dec(agent.macro_recall)}, F1 {dec(agent.macro_f1)}.
          {results?.verdicts.agent_reason ? ` ${results.verdicts.agent_reason}.` : ""}
        </p>
      ) : (
        <p className="text-[12px] text-fm-muted">{DASH} <span className="ml-1">Not measured: {results?.verdicts.agent_reason ?? "run scripts/run_eval.py after the decision agent has run."}</span></p>
      )}
    </Panel>
  );
}

export function NotMeasured({ results }: { results: EvalResults | null }) {
  const items = results?.not_measured ?? [];
  if (!results) {
    return (
      <p className="mt-3 rounded-fm border border-dashed border-fm-border px-3 py-2 text-[12px] text-fm-muted">
        <span className="fm-label mr-2">Eval report</span>data/eval_results.json is not present yet. Run <span className="font-mono">scripts/run_eval.py</span> to add image accuracy, macro F1, latency and cost.
      </p>
    );
  }
  if (items.length === 0) return null;
  return (
    <section className="mt-3 rounded-fm border border-dashed border-fm-border px-3 py-2" aria-label="Not measured">
      <p className="fm-label mb-1">Not measured yet</p>
      <ul className="list-disc pl-4 text-[12px] text-fm-muted">
        {items.map((m) => <li key={m}>{m}</li>)}
      </ul>
    </section>
  );
}
